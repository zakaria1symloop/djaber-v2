const wordsOf = (t: string) => ` ${foldText(t)} `;
const count = (t: string, set: Set<string>) => [...set].filter((w) => t.includes(` ${w} `)).length;

/**
 * The customer writes Modern Standard Arabic: their Arabic-script messages use MSA words and no darija word. Arabic-script lines only;
 * a conversation with one darija word anywhere is darija (the shop's default register).
 */
export const msaRegister = (customerHistory: string | undefined): boolean => {
  const lines = (customerHistory ?? '').split(/\n+/u).filter((l) => /\p{Script=Arabic}/u.test(l));
  if (!lines.length) return false;
  const all = wordsOf(lines.join(' '));
  return count(all, DARIJA_WORDS) === 0 && count(all, MSA_WORDS) >= 1;
};

